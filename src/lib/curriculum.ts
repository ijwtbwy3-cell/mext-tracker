export type FlatTopic = {
  id: string; // напр. «math-0-3»
  subjectId: SubjectId;
  sectionId: string; // напр. «math-0»
  sectionTitle: string;
  ord: number; // порядковый номер темы внутри предмета
  title: string;
  description: string;
  hours: number;
  difficulty: number;
  level: Level;
};

export type FlatSection = {
  id: string;
  subjectId: SubjectId;
  title: string;
  ord: number;
  topicIds: string[];
};

const buildFlat = () => {
  const sections: FlatSection[] = [];
  const topics: FlatTopic[] = [];
  for (const subject of SUBJECT_SEEDS) {
    subject.sections.forEach((section, sIdx) => {
      const sectionId = `${subject.id}-${sIdx}`;
      const topicIds: string[] = [];
      section.topics.forEach((tuple, tIdx) => {
        const [title, description, hours, difficulty, level] = tuple;
        const id = `${subject.id}-${sIdx}-${tIdx}`;
        topicIds.push(id);
        topics.push({
          id,
          subjectId: subject.id,
          sectionId,
          sectionTitle: section.title,
          ord: topics.filter((t) => t.subjectId === subject.id).length,
          title,
          description,
          hours,
          difficulty,
          level,
        });
      });
      sections.push({ id: sectionId, subjectId: subject.id, title: section.title, ord: sIdx, topicIds });
    });
  }
  return { sections, topics };
};

export const FLAT_SECTIONS: FlatSection[] = buildFlat().sections;
export const FLAT_TOPICS: FlatTopic[] = buildFlat().topics;

export type CurriculumStats = {
  subjects: number;
  sections: number;
  topics: number;
  hours: number;
  perSubject: { id: SubjectId; title: string; sections: number; topics: number; hours: number }[];
};

export function curriculumStats(): CurriculumStats {
  const perSubject = SUBJECT_SEEDS.map((s) => {
    const topics = FLAT_TOPICS.filter((t) => t.subjectId === s.id);
    return {
      id: s.id,
      title: s.title,
      sections: s.sections.length,
      topics: topics.length,
      hours: topics.reduce((acc, t) => acc + t.hours, 0),
    };
  });
  return {
    subjects: SUBJECT_SEEDS.length,
    sections: FLAT_SECTIONS.length,
    topics: FLAT_TOPICS.length,
    hours: FLAT_TOPICS.reduce((acc, t) => acc + t.hours, 0),
    perSubject,
  };
}
