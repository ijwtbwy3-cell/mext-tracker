export function PixelIcon({
  name,
  size = 16,
  className = "",
  color = "currentColor",
}: {
  name: IconName;
  size?: number;
  className?: string;
  color?: string;
}) {
  const grid = GRIDS[name];
  const rects: React.ReactElement[] = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let w = 1;
        while (x + w < row.length && row[x + w] === "#") w++;
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} />);
        x += w;
      } else {
        x++;
      }
    }
  });
  return (
    <svg
      viewBox="0 0 8 8"
      width={size}
      height={size}
      fill={color}
      shapeRendering="crispEdges"
      className={className}
      aria-hidden="true"
      style={{ display: "inline-block", verticalAlign: "middle" }}
    >
      {rects}
    </svg>
  );
}
